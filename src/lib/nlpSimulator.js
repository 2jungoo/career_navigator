function countKeywordMatches(text, keyword) {
  const safe = keyword.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const regex = new RegExp(safe, 'gi');
  return (text.match(regex) ?? []).length;
}

function scoreText(text) {
  const lower = text.toLowerCase();
  return Object.fromEntries(
    Object.entries(DOMAIN_KEYWORDS).map(([domain, { core, general }]) => {
      const coreHits = core.reduce(
        (sum, kw) => sum + countKeywordMatches(lower, kw.toLowerCase()), 0);
      const generalHits = general.reduce(
        (sum, kw) => sum + countKeywordMatches(lower, kw.toLowerCase()), 0);
      return [domain, coreHits * 3 + generalHits];
    })
  );
}

function normalizeScoreMap(scores) {
  const total = Object.values(scores).reduce((sum, value) => sum + value, 0) || 1;
  return Object.fromEntries(
    Object.entries(scores).map(([domain, score]) => [domain, Math.round((score / total) * 100)])
  );
}

function addVectorFeature(vector, feature, weight = 1) {
  if (!feature || feature.length < 2) return;
  vector.set(feature, (vector.get(feature) ?? 0) + weight);
}

// BoN n-gram 가중치: 2-gram은 접미어 변형 포착, 3-gram은 더 긴 형태소 연속에 가중.
// sweep 실험에서 (0.25, 0.35) 조합이 (0.5, 0.5), (1, 1) 대비 도메인 구분력이 높았음.
const BIGRAM_WEIGHT = 0.25;
const TRIGRAM_WEIGHT = 0.35;

// Hybrid 분류기 가중치: 가중치 민감도 분석에서 keyword_weight=[0.3~0.5] 구간이
// plateau(정체 구간)를 형성함. 0.45는 해당 구간 중앙값.
export const DEFAULT_KEYWORD_WEIGHT = 0.45;

// Evidence 임계값: keyword 점수 합이 이 값 미만이면 'insufficient'으로 처리.
// threshold ablation: 0→1→2→4에서 2가 accuracy/coverage 균형 최적.
export const DEFAULT_EVIDENCE_THRESHOLD = 2;

// Semantic-evidence 판정 기준: BoN 최고 도메인 코사인이 이 값 이상이고
// 2위 대비 이 배율 이상이어야 의미 있는 근거로 인정.
const SEMANTIC_LEADER_MIN = 0.16;
const SEMANTIC_LEADER_RATIO = 1.12;

// Keyword Baseline의 시맨틱 축: Bag-of-N-grams 가중 빈도 벡터.
// 진짜 SBERT 임베딩이 아니므로 어휘 겹침만 측정한다.
function buildBagOfNgrams(text) {
  const vector = new Map();
  const lower = (text ?? '').toLowerCase();
  const tokens = lower.match(/[a-z0-9+#]+|[가-힣]{2,}/g) ?? [];

  tokens.forEach((token) => {
    addVectorFeature(vector, `tok:${token}`, 1);
    if (/^[가-힣]+$/.test(token)) {
      for (let size = 2; size <= 3; size += 1) {
        for (let index = 0; index <= token.length - size; index += 1) {
          addVectorFeature(vector, `ng:${token.slice(index, index + size)}`, size === 2 ? BIGRAM_WEIGHT : TRIGRAM_WEIGHT);
        }
      }
    }
  });

  return vector;
}

function cosineSimilarity(left, right) {
  let dot = 0;
  let leftNorm = 0;
  let rightNorm = 0;

  left.forEach((value, key) => {
    leftNorm += value * value;
    dot += value * (right.get(key) ?? 0);
  });
  right.forEach((value) => {
    rightNorm += value * value;
  });

  if (!leftNorm || !rightNorm) return 0;
  return dot / (Math.sqrt(leftNorm) * Math.sqrt(rightNorm));
}

const PROFILE_EMBEDDINGS = Object.fromEntries(
  Object.entries(DOMAIN_SEMANTIC_PROFILES).map(([domain, profile]) => [domain, buildBagOfNgrams(profile)])
);

function scoreSemanticSimilarity(text) {
  const documentEmbedding = buildBagOfNgrams(text);

  return Object.fromEntries(
    Object.entries(PROFILE_EMBEDDINGS).map(([domain, profileEmbedding]) => [
      domain,
      cosineSimilarity(documentEmbedding, profileEmbedding),
    ])
  );
}

function buildHybridScores(keywordScores, semanticScores, keywordWeight = DEFAULT_KEYWORD_WEIGHT) {
  const semanticWeight = 1 - keywordWeight;
  const keywordNormalized = normalizeScoreMap(keywordScores);
  const semanticNormalized = normalizeScoreMap(semanticScores);

  return Object.fromEntries(
    Object.keys(keywordScores).map((domain) => [
      domain,
      Math.round((keywordNormalized[domain] ?? 0) * keywordWeight + (semanticNormalized[domain] ?? 0) * semanticWeight),
    ])
  );
}

function buildDomainEvidence(text) {
  const lower = text.toLowerCase();

  return Object.fromEntries(
    Object.entries(DOMAIN_KEYWORDS).map(([domain, { core, general }]) => {
      const matches = [...core.map((keyword) => ({ keyword, weight: 3 })), ...general.map((keyword) => ({ keyword, weight: 1 }))]
        .map(({ keyword, weight }) => ({
          keyword,
          count: countKeywordMatches(lower, keyword.toLowerCase()),
          weight,
        }))
        .filter(({ count }) => count > 0)
        .sort((left, right) => right.count * right.weight - left.count * left.weight)
        .slice(0, 8);

      return [domain, matches];
    })
  );
}


function extractKeywords(text) {
  const lower = text.toLowerCase();
  const frequencies = new Map();
  const allKeywords = Object.values(DOMAIN_KEYWORDS)
    .flatMap(({ core, general }) => [...core, ...general]);

  allKeywords.forEach((keyword) => {
    const count = countKeywordMatches(lower, keyword.toLowerCase());
    if (count > 0) {
      frequencies.set(keyword, (frequencies.get(keyword) ?? 0) + count);
    }
  });

  return Array.from(frequencies.entries())
    .sort((left, right) => right[1] - left[1])
    .slice(0, 18)
    .map(([keyword]) => keyword);
}

function buildRadarData(normalizedScores) {
  return Object.entries(normalizedScores)
    .filter(([domain]) => domain !== 'insufficient')
    .sort(([, a], [, b]) => b - a)
    .slice(0, 6)
    .map(([domain, score]) => ({
      subject: DOMAIN_LABELS[domain] ?? domain,
      A: Math.max(score, 5),
      fullMark: 100,
    }));
}

function normalizeInput(input) {
  if (typeof input === 'string') {
    return {
      text: input,
      meta: { sourceType: 'uploaded', title: '업로드 문서' },
    };
  }

  return {
    text: input?.text ?? '',
    meta: input?.meta ?? { sourceType: 'uploaded', title: '업로드 문서' },
  };
}

const STOPWORD_TOKENS = new Set([
  '교수', '교수님', '연구', '연구실', '연구소', '랩', '실험실',
  '대학', '대학교', '학과', '학부', '전공', '과정',
  '서울', '서울대학교', '카이스트', 'kaist', '포스텍',
  '분석', '개발', '경험', '이론', '학문', '학술',
  '중심', '기반', '관련', '활용',
]);

function collectMatchTokens(item) {
  const tokens = new Set();
  const push = (value) => {
    if (!value) return;
    String(value)
      .toLowerCase()
      .split(/[\s,/()[\]\-_.·・]+/u)
      .map((t) => t.trim())
      .filter((t) => t.length >= 2 && !STOPWORD_TOKENS.has(t))
      .forEach((t) => tokens.add(t));
  };

  push(item.label);
  push(item.field);
  (item.skills ?? []).forEach(push);
  (item.matchKeywords ?? []).forEach(push);
  return Array.from(tokens);
}

function pickRecommendations(sourceMap, rankedDomains, rawScores, normalizedScores, text, limit) {
  if (!rankedDomains.length || rankedDomains[0] === 'insufficient') {
    return [];
  }

  const lowerText = (text ?? '').toLowerCase();
  const primary = rankedDomains[0];
  const secondary = rankedDomains[1];
  const primaryRaw = rawScores[primary] ?? 0;
  const secondaryRaw = rawScores[secondary] ?? 0;

  const isDominant = primaryRaw >= secondaryRaw * 2 || secondaryRaw === 0;
  const secondaryRelevant = secondaryRaw >= primaryRaw * 0.4;

  const allowedDomains = new Set([primary]);
  if (!isDominant && secondaryRelevant) allowedDomains.add(secondary);

  const rankIndex = new Map(rankedDomains.map((domain, index) => [domain, index]));
  const scored = [];

  Object.entries(sourceMap).forEach(([domain, items]) => {
    if (!allowedDomains.has(domain)) return;
    const domainScore = normalizedScores[domain] ?? 0;
    const bonus = rankIndex.get(domain) === 0 ? 50 : 8;

    items.forEach((item) => {
      const tokens = collectMatchTokens(item);
      const allMatched = tokens.filter((token) => countKeywordMatches(lowerText, token) > 0);
      const matchedTokens = allMatched.slice(0, 5);
      const uniqueMatchCount = allMatched.length;
      const rankBonus = rankIndex.get(domain) === 0 ? 8 : 0;
      const baseFit = item.score ?? 70;
      const dynamicScore = domainScore + bonus + baseFit * 0.22 + uniqueMatchCount * 5;
      const displayScore = Math.round(
        Math.max(
          50,
          Math.min(
            97,
            baseFit * 0.35 + domainScore * 0.30 + rankBonus + matchedTokens.length * 7
          )
        )
      );
      scored.push({
        item: {
          ...item,
          // 일부 도메인은 summary를 문자열로 정의 → 노드/DetailPanel은 배열을 기대하므로 정규화
          summary: item.summary && !Array.isArray(item.summary) ? [item.summary] : item.summary,
          baseScore: item.score,
          score: displayScore,
          domain,
          matchScore: Math.round(dynamicScore),
          matchedTokens,
        },
        dynamicScore,
      });
    });
  });

  const seen = new Set();
  return scored
    .sort((left, right) => right.dynamicScore - left.dynamicScore)
    .filter(({ item }) => {
      if (seen.has(item.id)) return false;
      seen.add(item.id);
      return true;
    })
    .slice(0, limit)
    .map((entry) => entry.item);
}

export async function analyzeDocument(input, options = {}) {
  const { text, meta } = normalizeInput(input);

  if (import.meta.env?.DEV && !options.skipDelay) {
    await new Promise((resolve) => setTimeout(resolve, 900));
  }

  const splitResult = splitKoreanSentences(text);

  const rawScores = scoreText(text);
  const semanticScores = scoreSemanticSimilarity(text);        // BoN cosine
  const sbertScores = options.sbertScores ?? null;              // SBERT cosine (사전계산, 있을 때만)
  const keywordWeight = options.keywordWeight ?? DEFAULT_KEYWORD_WEIGHT;
  const hybridScores = buildHybridScores(rawScores, sbertScores ?? semanticScores, keywordWeight);
  const evidenceByDomain = buildDomainEvidence(text);
  const totalRawScore = Object.values(rawScores).reduce((sum, value) => sum + value, 0);
  const evidenceThreshold = options.evidenceThreshold ?? DEFAULT_EVIDENCE_THRESHOLD;
  const scoringMode = options.scoringMode ?? 'hybrid';
  // sbert-only: SBERT 유사도만으로 분류 (사전계산 없으면 BoN 폴백)
  // head-only / head-hybrid: 학습된 분류 헤드 (sbertScores 자리에 헤드 확률 주입)
  const classifierScores =
    scoringMode === 'keyword'    ? normalizeScoreMap(rawScores) :
    scoringMode === 'sbert-only' ? normalizeScoreMap(sbertScores ?? semanticScores) :
    scoringMode === 'head-only'  ? normalizeScoreMap(sbertScores ?? semanticScores) :
    scoringMode === 'head-hybrid'? hybridScores :
                                    hybridScores;
  const sortedSemanticDomains = Object.entries(semanticScores).sort(([, left], [, right]) => right - left);
  const semanticLeader = sortedSemanticDomains[0]?.[1] ?? 0;
  const semanticRunnerUp = sortedSemanticDomains[1]?.[1] ?? 0;
  const hasSemanticEvidence = semanticLeader >= SEMANTIC_LEADER_MIN && semanticLeader >= semanticRunnerUp * SEMANTIC_LEADER_RATIO;
  const hasEnoughEvidence =
    totalRawScore >= evidenceThreshold ||
    ((scoringMode === 'hybrid' || scoringMode === 'head-hybrid') && hasSemanticEvidence) ||
    ((scoringMode === 'head-only' || scoringMode === 'head-hybrid') && sbertScores !== null);

  const normalizedScores = classifierScores;

  const sortedDomains = Object.entries(classifierScores).sort(([, left], [, right]) => right - left);
  const primaryDomain = hasEnoughEvidence ? (sortedDomains[0]?.[0] ?? 'insufficient') : 'insufficient';
  const rankedDomains = hasEnoughEvidence ? sortedDomains.map(([domain]) => domain) : [];
  const domainEvidence = hasEnoughEvidence
    ? (evidenceByDomain[primaryDomain] ?? [])
    : [];

  const fullSentences = splitResult.map((s) => ({ ...s }));

  const jobRecommendations = pickRecommendations(
    JOB_RECOMMENDATIONS,
    rankedDomains,
    rawScores,
    normalizedScores,
    text,
    5
  );
  const labRecommendations = pickRecommendations(
    LAB_RECOMMENDATIONS,
    rankedDomains,
    rawScores,
    normalizedScores,
    text,
    4
  );

  return {
    primaryDomain,
    domainLabel: JOB_CATEGORIES[primaryDomain]?.label ?? primaryDomain,
    domainColor: JOB_CATEGORIES[primaryDomain]?.color ?? '#3b82f6',
    keywords: extractKeywords(text),
    radarData: buildRadarData(normalizedScores),
    originalText: text,
    fullSentences,
    jobRecommendations,
    labRecommendations,
    normalizedScores,
    rawScores,
    semanticScores,
    hybridScores,
    domainEvidence,
    hasEnoughEvidence,
    documentMeta: meta,
  };
}

